#!/usr/bin/env node
/**
 * sync-published-posts.mjs — published posts + engagement → social_published
 * FOR THE COMMONS GOOD — reusable pattern, candidate for shared WSP001 library
 *
 * STAGE 4 of the social pipeline. This is the step that closes the loop:
 *
 *   published post + engagement metrics → social_published (pgvector)
 *                                       → chatbot can discuss Scott's presence
 *                                       → SirScottA2A sees what performed
 *                                       → next generation is better informed
 *
 * Without this stage the pipeline is open-loop: it generates forever and never
 * learns. With it, engagement becomes retrievable context.
 *
 * Usage:
 *   node scripts/sync-published-posts.mjs --file published.json
 *   node scripts/sync-published-posts.mjs --file published.json --commit
 *   node scripts/sync-published-posts.mjs --sample
 *
 * Input shape (JSON array, or { posts: [...] }):
 *   {
 *     "content": "the post body as published",
 *     "platform": "linkedin",
 *     "published_at": "2026-09-10",
 *     "url": "https://...",
 *     "engagement": { "likes": 42, "comments": 7, "shares": 3, "impressions": 5100 },
 *     "generated_by": "sirscotta2a",
 *     "topic": "SeaTrace milestone"
 *   }
 *
 * HONESTY NOTE: engagement is recorded as the numbers supplied, with the
 * capture date attached. Metrics keep climbing after capture, so a chunk is a
 * snapshot and says so. Re-running with fresh numbers creates a NEW chunk
 * (different text → different content hash) rather than updating the old one;
 * that is intentional, the history of how a post performed over time is
 * itself signal. Set --latest-only to skip posts already carrying a snapshot.
 */

import { readFileSync, existsSync } from "node:fs";
import { runBatch, parseArgs } from "./lib/ingest-client.mjs";

const PARTITION = "social_published";

const SAMPLE = [
  {
    content:
      "We spent six months on the DeckSide pipeline and the hard part was never the cryptography. It was reconciling ASFIS species codes across three jurisdictions.",
    platform: "linkedin",
    published_at: "2026-09-10",
    url: "https://linkedin.example/posts/1",
    engagement: { likes: 42, comments: 7, shares: 3, impressions: 5100 },
    generated_by: "sirscotta2a",
    topic: "SeaTrace DeckSide",
  },
];

function engagementSummary(e) {
  if (!e || typeof e !== "object") return "Engagement metrics were not captured.";
  const parts = [];
  if (Number.isFinite(e.impressions)) parts.push(`${e.impressions} impressions`);
  if (Number.isFinite(e.likes)) parts.push(`${e.likes} reactions`);
  if (Number.isFinite(e.comments)) parts.push(`${e.comments} comments`);
  if (Number.isFinite(e.shares)) parts.push(`${e.shares} shares`);
  if (parts.length === 0) return "Engagement metrics were not captured.";

  // Engagement rate is only meaningful with an impression denominator.
  let rate = "";
  if (Number.isFinite(e.impressions) && e.impressions > 0) {
    const interactions = (e.likes || 0) + (e.comments || 0) + (e.shares || 0);
    rate = ` That is an engagement rate of ${((interactions / e.impressions) * 100).toFixed(2)}%.`;
  }
  return `It received ${parts.join(", ")}.${rate}`;
}

function toChunk(post, sourceName, capturedAt) {
  const platform = post.platform || "unknown platform";
  const when = post.published_at || "an unrecorded date";
  const by = post.generated_by === "sirscotta2a" ? "generated by SirScottA2A-STUDIO" : "published manually";
  const topic = post.topic ? ` Topic: ${post.topic}.` : "";

  const content =
    `Published ${platform} post (${by}) from ${when}.${topic}\n\n` +
    `Post text: ${String(post.content).trim()}\n\n` +
    `${engagementSummary(post.engagement)} ` +
    `Metrics are a snapshot captured ${capturedAt} and may have grown since.`;

  return {
    content,
    partition: PARTITION,
    source: `social_published:${platform}:${when}`,
    modality: "text",
    metadata: {
      partition: PARTITION,
      platform,
      published_at: post.published_at || null,
      url: post.url || null,
      engagement: post.engagement || null,
      generated_by: post.generated_by || null,
      topic: post.topic || null,
      metrics_captured_at: capturedAt,
      synced_by: "sync-published-posts.mjs",
      ingest_source: sourceName,
    },
  };
}

function loadPosts(args) {
  if (args.sample) return { items: SAMPLE, name: "--sample fixture" };

  if (!args.file || args.file === true) {
    console.error("Usage: node scripts/sync-published-posts.mjs --file <published.json> [--commit]");
    console.error("       node scripts/sync-published-posts.mjs --sample");
    process.exit(1);
  }
  if (!existsSync(args.file)) {
    console.error(`✗ File not found: ${args.file}`);
    process.exit(1);
  }
  const parsed = JSON.parse(readFileSync(args.file, "utf-8"));
  const items = Array.isArray(parsed) ? parsed : parsed?.posts;
  if (!Array.isArray(items)) {
    console.error("✗ Expected a JSON array, or an object with a `posts` array.");
    process.exit(1);
  }
  return { items, name: args.file };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const { items, name } = loadPosts(args);
  const capturedAt = new Date().toISOString().slice(0, 10);

  const chunks = [];
  let rejected = 0;
  for (const post of items) {
    if (!post?.content || typeof post.content !== "string" || post.content.trim().length < 20) {
      rejected++;
      continue;
    }
    chunks.push(toChunk(post, name, capturedAt));
  }

  console.log(`Source: ${name}`);
  console.log(`  ${chunks.length} published posts, ${rejected} rejected (missing or too-short content)`);
  if (args.sample && !args.commit) {
    console.log("\nGenerated chunk text:\n");
    console.log(chunks[0].content.split("\n").map((l) => `  ${l}`).join("\n"));
    console.log();
  }

  if (chunks.length === 0) process.exit(1);
  await runBatch(chunks, { dryRun: !args.commit, label: "published posts" });
}

main().catch((err) => {
  console.error(`\n✗ ${err.message}`);
  process.exit(1);
});
